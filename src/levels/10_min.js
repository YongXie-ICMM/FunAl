FunAl.register({
  id: 'minrule',
  title: '加号变成挑小的',
  goal: '让学习者自己选出「挑小的再加本级费用」，并弄清计数题为什么不加代价、最优化题为什么要加。',
  minutes: 3,
  async run(t) {
    const D = FunAl.data.toll;
    const tolls = D.tolls;

    await t.say('老办法搬过来：**站在第 6 级，回头看最后一脚。**');

    await t.ask.multi('你的最后一脚，是从哪一级踩上来的？', ['第 3 级', '第 4 级', '第 5 级', '第 6 级'], {
      correct: [1, 2],
      feedback: (got) => {
        if (got.includes(3)) return '第 6 级是你现在站的地方，没法从它踩到它。';
        if (got.includes(0)) return '从第 3 级到第 6 级要跨 3 级，规则没变，一脚最多 2 级。';
        return '一脚只能 1 级或 2 级。从第 6 级往回退 1 级、退 2 级，是哪两级？';
      },
      explainRight: '对。**跟数走法时一模一样：只有两个来源。** 换了问题，这一步没变。',
      hints: ['规则没变，一脚还是只能走 1 级或 2 级。'],
    });

    await t.say('那这两个来源怎么合起来？数走法的时候是**相加**。这次呢？');
    await t.say('这两个数先由我给你（下一屏你自己算）：');

    t.note('已知', `**到第 5 级，最省 ${D.best[5]} 元。**\n\n**到第 4 级，最省 ${D.best[4]} 元。**\n\n第 6 级自己的过路费是 **${tolls[6]} 元**。`);

    await t.ask.choice('那「到第 6 级最省多少」等于什么？', [
      `挑小的(${D.best[5]}, ${D.best[4]}) + ${tolls[6]}`,
      `${D.best[5]} + ${D.best[4]} + ${tolls[6]}`,
      `挑大的(${D.best[5]}, ${D.best[4]}) + ${tolls[6]}`,
      `挑小的(${D.best[5]}, ${D.best[4]})`,
    ], {
      correct: 0,
      feedback: {
        1: `想想这两个数是什么：${D.best[5]} 元是**走第 5 级那条路**的花费，${D.best[4]} 元是**走第 4 级那条路**的花费。\n\n它们是**两条不同的路**各自的价钱。你最后只会走其中一条，只会收到**一张收据**。\n\n把两张收据加起来，等于假设你两条路都走了一遍。`,
        2: '题目问的是**最少**花多少。挑大的那个，等于故意选贵的那条路。',
        3: `方向对了，但漏了一样东西：你**踩上第 6 级**这一脚本身也要付钱，第 6 级贴着 ${tolls[6]} 元。`,
      },
      explainRight: `对：**挑小的(${D.best[5]}, ${D.best[4]}) + ${tolls[6]}**。`,
      hints: [
        '这两个数是两条不同的路各自的花费。你只走一条。',
        '所以是在两个数里**挑一个**，不是把它们加起来。挑哪个？',
        `挑完之后还差一样东西没算：踩上第 6 级要付的那 ${tolls[6]} 元。`,
      ],
    });

    await t.ask.number(`那算一下：到第 6 级最省多少元？`, {
      answer: D.bestCost,
      unit: ' 元',
      feedback: (v) => {
        if (v === D.best[5] + D.best[4] + tolls[6]) return '你把两个数加起来了。它们是两条路各自的花费，你只走一条，只挑一个。';
        if (v === D.best[5]) return `挑对了小的那个（${D.best[5]}），但还没加上踩第 6 级的 ${tolls[6]} 元。`;
        if (v === D.best[4] + tolls[6]) return `你挑的是大的那个（${D.best[4]}）。题目问最少，所以挑小的那个。`;
        return `不对。先在 ${D.best[5]} 和 ${D.best[4]} 里挑小的，再加上第 6 级的 ${tolls[6]} 元。`;
      },
      hints: [`${D.best[5]} 和 ${D.best[4]}，小的是哪个？`, `${D.best[5]} + ${tolls[6]} = ?`],
    });
    t.right(`**${D.best[5]} + ${tolls[6]} = ${D.bestCost} 元。** 和你上一屏试出来的最省数字一样。`);

    await t.say('现在回答一个很多人会卡住的问题。');

    await t.ask.choice('数走法的时候，最后一脚**不用加**任何东西，直接把两堆相加。算钱的时候，却要**加上本级的过路费**。为什么不一样？', [
      '因为数走法时，最后那一脚不会多造出一条路，它只是把两堆路线并在一起；而算钱时，那一脚本身要付钱。',
      '因为计数题和最优化题是两套完全不同的方法。',
    ], {
      correct: 0,
      feedback: {
        1: '两者其实是同一套方法：都是「看最后一步、拆成小题、从小到大算」。不一样的只有**怎么合并**这一步。',
      },
      explainRight: '对。**最后一脚在计数里不产生新路线，在算钱里却要真金白银。** 所以一个不加，一个要加。',
      hints: [
        '问自己：走完最后那一脚，路线的**条数**会变多吗？',
        '再问：走完最后那一脚，你的**钱包**会变少吗？',
      ],
    });

    t.note('同一套办法，只换了一个动作', '先把每一种「最后一步」各自算成一个数——**那一步自己的代价，算进它自己那一支**。然后：\n\n**数「有几种」** → 把这些数**加起来**。\n\n**求「最少」** → 在这些数里**挑小的**。\n\n**求「最多」** → 在这些数里**挑大的**。\n\n这道题里两支的代价碰巧一样（都是踩上第 6 级的 ' + tolls[6] + ' 元），所以写成「挑小的再加 ' + tolls[6] + '」也对。但**别把这当成通则**——有的题里，不同的最后一步代价不同，甚至有一支根本不花钱。到时候就得老老实实一支一支算完再挑。\n\n前面找最后一步、定起步格、从小往大填，全都一模一样。');

    await t.say('下一屏，你自己把这张最省表从头填一遍——而且填完之后，我要你**亲手把那条最省路线倒着找回来**。');
    t.done();
  },
});
