FunAl.register({
  id: 'boundary',
  title: '第 0 级填几',
  goal: '让学习者用刚推出的规律反推出「到第 0 级 = 1」，而不是被告知；并用规律算到第 6 级，跟开场的猜测对账。',
  minutes: 3,
  async run(t) {
    const D = FunAl.data.ways;

    await t.say('你手上现在有一条规律：\n\n**到第 k 级的走法数 = 到第 k−1 级的走法数 + 到第 k−2 级的走法数**');
    await t.say('把你已经**亲手数出来**的数字先摆好。下面每一格就是一级台阶，格子里写「从地面走到这一级，有几种走法」。');

    const box = t.canvas();
    const row = FunAl.widgets.cells(box, {
      n: 6,
      label: (i) => (i === 0 ? '地面' : `第 ${i} 级`),
      values: { 1: 1, 2: 2, 3: 3, 4: 5 },
      title: '每一级：有几种走法',
    });
    row.setSub(1, '数出来的'); row.setSub(2, '数出来的'); row.setSub(3, '数出来的'); row.setSub(4, '数出来的');

    await t.say('第 1 到第 4 级你都数过了。现在从第 5 级往上，可以直接用规律算——**但先看看最左边那一格。**');
    await t.say('地面那一格，写的是「从地面走到地面，有几种走法」。');

    row.mark(0, 'active');
    await t.ask.number('地面那一格，填几？', {
      answer: 1,
      unit: ' 种',
      button: '填上',
      feedback: (v) => {
        if (v === 0) {
          return '很多人都填 0，理由是「我一步都没走」。听起来很有道理，但我们**检查一下**。\n\n你刚推出的规律说：**到第 2 级 = 到第 1 级 + 到地面**。到第 1 级是 1，地面按你填的是 0，那到第 2 级就该是 **1 + 0 = 1** 种。\n\n可你上一屏亲手数过，到第 2 级有 **2 种**（+1+1 和 +2）。对不上。\n\n那地面这一格得填几，才能让 1 + ? = 2？';
        }
        if (v === 2) return '2 的话，到第 2 级就成了 1 + 2 = 3 种。可你亲手数出来是 2 种。再调一下。';
        if (v < 0) return '走法数不会是负的。它是「有几条路」，最少也是 0 条。';
        return `填 ${v} 的话，到第 2 级就成了 1 + ${v} = ${1 + v} 种。可你亲手数出来是 **2 种**。要让 1 + ? = 2，问号得是几？`;
      },
      hints: [
        '别凭感觉。用规律去卡它：到第 2 级 = 到第 1 级 + 到地面。',
        '到第 1 级是 1，到第 2 级你数出来是 2。那么 1 + ? = 2。',
      ],
    });
    row.set(0, 1, 'given');
    row.setSub(0, '逼出来的');
    row.clearMarks();

    t.right('**1。** 注意这个 1 不是我告诉你的，也不是背来的——是你用自己推出的规律，反过来把它逼出来的。');

    await t.say('那它是什么意思？「从地面走到地面」有 1 种走法：**一步都不走**。');
    await t.say('就像「什么都不买」也算一种买法。空着的那一趟，也是一趟。');

    t.note('起步格怎么定（这条以后每道题都要用）', '起步格不是背下来的。**把规律往下多套一格，看这一格必须填几，才对得上你亲手数出来的结果。**\n\n后面换了题目，起步格的数字会变（有时是 0，有时是 1）。每次都用这个办法逼一次，就不会记混。');

    await t.say('好，规律有了，起步格也定了。往上算吧。');

    row.links(5, [4, 3], ['+1', '+2']);
    t.hints(['看第 5 级左边那两条弧线，它们指向第 4 级和第 3 级。', '第 4 级是 5 种，第 3 级是 3 种。把这两个数加起来。']);
    await row.fill(5, {
      answer: D.table[5],
      onWrong: (v) => {
        const a = D.table[4], b = D.table[3];
        if (v === a + b + 1) t.wrong(`比正确答案多了 1。这一屏不用加「最后一步」本身——最后一步不制造新走法，它只是把两堆合起来。`);
        else if (v === a) t.wrong(`${a} 是「到第 4 级」那一格的数字。到第 5 级要把**两格**加起来：第 4 级的 ${a}，加上第 3 级的 ${b}。`);
        else if (v === a * b) t.wrong(`这里是相加不是相乘。两堆路线摆在一起，总数是 ${a} 条加 ${b} 条。`);
        else t.wrong(`不对。看上面那两条弧线：到第 5 级只能从第 4 级跨 1 级上来，或者从第 3 级跨 2 级上来。把这两格的数字加起来。`);
      },
      onRight: () => { row.markLink(4, 'pick'); row.markLink(3, 'pick'); t.right(`**${D.table[4]} + ${D.table[3]} = ${D.table[5]}**`); },
    });
    t.clearHints();
    await t.pause(1500);          // let the two chosen arcs stay lit for a moment

    row.clearLinks();
    row.links(6, [5, 4], ['+1', '+2']);
    t.hints(['到第 6 级的最后一脚，是从第 5 级跨 1 级，还是从第 4 级跨 2 级。', '第 5 级是 8 种，第 4 级是 5 种。']);
    await row.fill(6, {
      answer: D.table[6],
      onWrong: (v) => t.wrong(v === D.table[5] + D.table[3]
        ? '加错了一格。到第 6 级的两个来源是第 5 级和第 4 级，不是第 5 级和第 3 级。'
        : `不对。到第 6 级 = 到第 5 级（${D.table[5]}）+ 到第 4 级（${D.table[4]}）。`),
      onRight: () => { row.markLink(5, 'pick'); row.markLink(4, 'pick'); },
    });
    t.clearHints();
    await t.pause(1500);
    row.clearLinks();

    const bet = t.recallOne({ screen: 'hook', kind: 'number' });
    t.right(`**到第 6 级：${D.table[6]} 种。**`);
    if (bet) {
      const diff = Number(bet.answer) - D.table[6];
      await t.say(`回头看一眼：开场你押的是 **${bet.answer} 种**，真实答案是 **${D.table[6]} 种**。`
        + (diff === 0 ? '\n\n你押中了。不过重点不是押中，是你现在**知道为什么**是 13。'
          : `\n\n差了 ${Math.abs(diff)}。没关系——重点是这个 13 不是猜的，是你一格一格算出来的。`));
    }

    await t.ask.predict('顺便看一眼这一整排数字：1、1、2、3、5、8、13。你见过它吗？', [
      '见过，好像有个名字',
      '没见过',
    ]);
    await t.say('它叫**斐波那契数列**。你要是认出来了，那你眼力不错——我们没打算瞒着你。');
    await t.say('不过名字不重要。重要的是：这串数不是查来的，是你从「最后一脚只有两种」一路推出来的。**换一道题，规律就变了，但推的办法不变。**');

    t.note('停一下，你刚才做了什么', '你把一整排格子从左往右填满了，每一格都用它左边两格算出来。\n\n这条路叫**从下往上算**。它很自然——但它不是大多数人的第一反应。');

    await t.say('大多数人拿到那条规律，第一反应是**反过来问**：\n\n「到第 6 级？那我得先知道第 5 级和第 4 级。到第 5 级？那我得先知道第 4 级和第 3 级……」一路往下问。');
    await t.say('写代码的人尤其会这样，因为规律本来就是那么写的：它把大的用小的表示。');
    await t.say('下一屏，你亲手当一次那台**从上往下问**的机器。你会发现一点问题。');

    t.done();
  },
});
