FunAl.register({
  id: 'takeaway',
  title: '带走一张清单',
  goal: '让学习者回看自己走过的路，把四问排成清单，并在三道没见过的题上只做「认题」练习。',
  minutes: 4,
  async run(t) {
    const W = FunAl.data.ways, D = FunAl.data.toll, C = FunAl.data.coins;

    await t.say('结束之前，先回头看看你自己做过什么。');

    const log = t.recall();
    const answered = log.filter((e) => e.correct !== undefined).length;
    const gotWrong = log.filter((e) => e.correct === false).length;
    const bet1 = t.recallOne({ screen: 'hook', kind: 'number' });
    const betToll = t.recallOne({ screen: 'toll', kind: 'number' });
    const betCoin = t.recallOne({ screen: 'coins', kind: 'number' });

    const lines = [];
    if (bet1) lines.push(`开场你押「到第 6 级有 ${bet1.answer} 种走法」，最后你自己算出了 **${W.table[6]} 种**。`);
    if (betToll) lines.push(`过路费那题你押 ${betToll.answer} 元，自己填表填出了 **${D.bestCost} 元**。`);
    if (betCoin) lines.push(`硬币那题你押 ${betCoin.answer} 枚，自己填表填出了 **${C.best} 枚**。`);
    lines.push(`一路上你回答了 **${answered}** 个有对错的问题${gotWrong ? `，其中 **${gotWrong}** 次先答错了再改对` : ''}。`);
    t.note('你走过的路', lines.join('\n\n') + (gotWrong ? '\n\n答错的那几次才是真正学到东西的地方。' : ''));

    await t.say('你做完了三道题：**数走法**、**算最省的钱**、**凑最少的硬币**。三道题长得完全不一样，但你每次做的事是同一件。');
    await t.say('把那件事排成顺序。**下面四句话，哪一句得先问？**');

    await t.ask.order('按你实际做事的顺序，把这四句排好：', [
      '**一格代表什么？** 找一个能从小排到大的编号，格子里写题目问的那个东西。',
      '**最后一步有哪几种可能？** 每一种，都对应一个更小的格子。',
      '**几个来源怎么合起来？** 数「有几种」就相加；求「最少」就挑小的，求「最多」就挑大的，再加上这一步自己的代价。',
      '**起步格填几？** 看格子里写的是什么，最小的那种情况它是多少。',
    ], {
      shuffled: [2, 0, 3, 1],
      feedback: (idx, next) => {
        const names = ['「一格代表什么」', '「最后一步有哪几种」', '「怎么合起来」', '「起步格填几」'];
        if (next === 0) return `还不到这一句。你得**先知道格子是什么**，才谈得上后面几步。`;
        if (idx === 0) return '这一句你已经放过了。';
        return `${names[idx]} 还早。在问它之前，你得先答完前面那几句——你回想一下在硬币那道题上，你是按什么顺序答的。`;
      },
      explainRight: '这就是你在硬币那道题上的实际顺序。',
      hints: [
        '想想硬币那一屏，我一共问了你四个问题，第一个问的是什么？',
        '顺序是：格子是什么 → 最后一步有哪几种 → 怎么合 → 起步格。',
      ],
    });

    t.note('把这张清单带走', '**一、一格代表什么？**（能从小排到大，格子里写题目问的东西）\n\n**二、最后一步有哪几种可能？**（每一种对应一个更小的格子）\n\n**三、几个来源怎么合起来？**（几种 → 相加；最少 → 挑小的；最多 → 挑大的；别忘了加上这一步自己的代价）\n\n**四、起步格填几？**（看格子里写的是什么，最小情况下它是多少）\n\n然后从小到大，一格一格填过去。');

    await t.say('最后练三道。**只问第一句：一格代表什么。不用算。**');

    await t.ask.choice('**（一）** 一只青蛙，一次能跳 1 格或者 3 格。跳到第 10 格，有几种跳法？', [
      '每一格一格，格子里写「跳到这一格有几种跳法」；来路是前 1 格和前 3 格。',
      '每一种跳法一格。',
      '两格：一格写「跳 1 格的次数」，一格写「跳 3 格的次数」。',
    ], {
      correct: 0,
      feedback: {
        1: '跳法有多少种正是要求的答案，你事先不知道有几种，没法给它们编号。',
        2: '这两个数字不能从小排到大，也没法用「更小的同类题」往下拆。',
      },
      explainRight: '对。**跟爬楼梯是同一道题**，只是最后一脚从「1 级或 2 级」变成了「1 格或 3 格」。',
      hints: ['这道题跟你做的第一道题，差别只有一处。哪一处？'],
    });

    await t.ask.choice('**（二）** 一排房子，每家有些钱。不能偷相邻的两家。最多能偷多少？', [
      '每个位置一格，格子里写「只看前面这几家，最多能偷多少」；最后一步是「偷不偷这一家」。',
      '每个位置一格，格子里写「这一家偷不偷」。',
      '每个位置一格，格子里写「这一家有多少钱」。',
    ], {
      correct: 0,
      feedback: {
        1: '「偷不偷」是**选择**，不是答案。格子里要写的是题目问的那个东西——最多能偷多少**钱**。',
        2: '这是题目给的条件，不是你要算的东西。格子里写的应该是**答案**。',
      },
      explainRight: '对。注意这道题的「最后一步」不是「从哪儿来」，而是「**偷还是不偷**」。\n\n偷 → 这家的钱 + 前 k−2 家的答案（隔壁不能偷）。\n不偷 → 前 k−1 家的答案。\n\n**求「最多」，所以挑大的。** 四问一个没少。',
      hints: [
        '题目问的是「最多能偷多少钱」。那格子里该写什么？',
        '这道题的「最后一步」不是从哪一级走上来，而是一个**选择**：这一家，偷还是不偷。',
      ],
    });

    await t.ask.choice('**（三）** 一个机器人在方格纸上，只能向右或者向下走。从左上角到右下角，有几条路？', [
      '每个格子一格，写「到这个格子有几条路」；来路是左边一格和上面一格。格子排成一**面**，不是一排。',
      '每一行一格，写「这一行有几条路」。',
      '这道题用不了这套办法。',
    ], {
      correct: 0,
      feedback: {
        1: '一行里的每个格子答案都不一样，一行只写一个数是不够的。**位置要用两个数才说得清：第几行、第几列。**',
        2: '能用。只是「我在哪儿」这次要用两个数字来说（第几行第几列），所以格子铺成一面而不是排成一排。',
      },
      explainRight: '对。**这就是那句判据在起作用**：站在这里，光知道「第几行」不够，还得知道「第几列」。所以格子里要记的东西多了一样，一排就变成了一面。\n\n跟你在罚款那一屏见过的一模一样。办法没变。',
      hints: [
        '在方格纸上，你要说清「我现在在哪儿」，需要几个数字？',
        '回想罚款那一屏：光知道「我在第几级」不够的时候，一排格子变成了几排？',
      ],
    });

    await t.ask.choice('**（四）** 最后一道，回到开场那句话。**手机地图给你算最快路线**——一格代表什么？', [
      '每个**路口**一格，写「从出发地到这个路口最快要几分钟」；来路是通到它的那几条路，**挑小的**再加上那段路要花的时间。',
      '每条**路**一格，写「这条路要开几分钟」。',
      '每个**目的地**一格，写「到这个目的地最快几分钟」。',
    ], {
      correct: 0,
      feedback: {
        1: '「这条路要开几分钟」是地图**已经知道的条件**，不是要算的答案。格子里写的应该是你还不知道、需要算出来的那个东西。',
        2: '你只有一个目的地，那就只有一格，没法从小往大填。中间那些路口才是你需要一格一格填过去的东西。',
      },
      explainRight: '对。**这就是你刚才填的最省表**，只不过格子不再排成一排，而是散在地图上。\n\n「挑小的再加这一段的时间」——一模一样。',
      hints: [
        '地图上什么东西是**很多个**、而且可以一个一个算过去的？',
        '想想过路费楼梯：格子是「台阶」，格子里写「到这一级最少花多少」。地图上跟「台阶」对应的是什么？',
      ],
    });

    await t.say('四道题，你都没算，但你都知道该从哪儿下手了。**这就是这门课想给你的东西。**');

    t.note('开场那三个例子，现在都拆得开了', '**地图算最快路线** → 你刚刚自己答出来了。\n\n**拼写检查把「recieve」改成「receive」** → 格子里写「把这半截改成那半截，最少改几个字母」；最后一步有三种：删一个、加一个、换一个；**挑小的**再 +1。（这题的格子要用两个数才说得清「改到哪儿了」，所以铺成一面。）\n\n**输入法猜你下一个字** → 同一套路：每多打一个字就往前推一格，算过的不重算。\n\n**跟你刚才填的那几张表，是同一件事。**');

    await t.say('课程到这里就结束了。');
    await t.say('如果你还有想不通的地方，页面底部有「问导师」（开着的话）。它不会直接给你答案——跟这门课一样，它只会往你想通的方向推一把。');

    t.aside('给写过代码的人：三道题的三行代码', '**爬楼梯**\n`f[0]=1; f[1]=1`\n`for k in 2..n: f[k] = f[k-1] + f[k-2]`\n\n**过路费楼梯**\n`g[0]=0; g[1]=toll[1]`\n`for k in 2..n: g[k] = toll[k] + min(g[k-1], g[k-2])`\n\n**凑硬币**\n`h[0]=0; 其余先填一个很大的数`\n`for a in 1..target: h[a] = min(h[a-c] for c in coins if c<=a) + 1`\n\n三段循环长得几乎一样。变的只有三处：格子的编号、来路、以及合并用的是 `+` 还是 `min`。');

    t.done({ label: '回到目录' });
  },
});
